inline u32 readU32(const u8 *p) {
    return static_cast<u32>(p[0]) |
           (static_cast<u32>(p[1]) << 8) |
           (static_cast<u32>(p[2]) << 16) |
           (static_cast<u32>(p[3]) << 24);
}

// SCXorShift32.cs: initial state advances once per set bit in the seed.
struct SCXorShift32 {
    u32 state;
    u32 counter;

    static u32 advance(u32 x) {
        x ^= x << 2;
        x ^= x >> 15;
        x ^= x << 13;
        return x;
    }

    explicit SCXorShift32(u32 seed) : state(seed), counter(0) {
        const int bits = __builtin_popcount(seed);
        for (int i = 0; i < bits; ++i) state = advance(state);
    }

    u8 next() {
        const u8 result = static_cast<u8>(state >> (counter * 8));
        if (counter == 3) {
            state = advance(state);
            counter = 0;
        } else {
            ++counter;
        }
        return result;
    }

    u32 next32() {
        return static_cast<u32>(next()) |
               (static_cast<u32>(next()) << 8) |
               (static_cast<u32>(next()) << 16) |
               (static_cast<u32>(next()) << 24);
    }
};

inline void cryptStaticXorpad(std::vector<u8> &data) {
    if (data.empty()) return;
    constexpr std::size_t STEP = sizeof(STATIC_XORPAD) - 1;
    const std::size_t iterations = (data.size() - 1) / STEP;
    std::size_t off = 0;
    for (std::size_t i = 0; i < iterations; ++i) {
        const std::size_t n = std::min<std::size_t>(sizeof(STATIC_XORPAD), data.size() - off);
        for (std::size_t j = 0; j < n; ++j) data[off + j] ^= STATIC_XORPAD[j];
        off += STEP;
    }
    const std::size_t remaining = data.size() - off;
    for (std::size_t j = 0; j < remaining; ++j) data[off + j] ^= STATIC_XORPAD[j];
}

struct BlockView {
    bool found = false;
    u32 key = 0;
    u8 type = 0;
    const u8 *data = nullptr;
    std::size_t size = 0;
};

inline s32 typeSize(u8 type) {
    switch (type) {
        case 1: case 2: return 0;   // Bool1 / Bool2 have no data bytes
        case 3: return 1;          // Bool3
        case 4: case 5: return 0;  // Object / Array handled separately
        case 8: return 1;          // Byte
        case 9: return 2;          // UInt16
        case 10: return 4;         // UInt32
        case 11: return 8;         // UInt64
        case 12: return 1;         // SByte
        case 13: return 2;         // Int16
        case 14: return 4;         // Int32
        case 15: return 8;         // Int64
        case 16: return 4;         // Single
        case 17: return 8;         // Double
        default: return -1;
    }
}

inline bool parseBlocks(const std::vector<u8> &data, u32 wantedKey, BlockView &out) {
    std::size_t off = 0;
    while (off + 5 <= data.size()) {
        const u32 key = readU32(data.data() + off);
        off += 4;
        SCXorShift32 rng(key);
        const u8 type = static_cast<u8>(data[off] ^ rng.next());
        ++off;

        if (type == 1 || type == 2) continue;  // boolean blocks have no payload

        s32 length = 0;
        if (type == 4) {  // Object: 32-bit byte length
            if (off + 4 > data.size()) return false;
            length = static_cast<s32>(readU32(data.data() + off) ^ rng.next32());
            off += 4;
        } else if (type == 5) {  // Array: 32-bit count + subtype
            if (off + 5 > data.size()) return false;
            const s32 count = static_cast<s32>(readU32(data.data() + off) ^ rng.next32());
            off += 4;
            const u8 subtype = static_cast<u8>(data[off] ^ rng.next());
            ++off;
            const s32 subSize = typeSize(subtype);
            if (count < 0 || subSize <= 0) return false;
            if (static_cast<std::size_t>(count) > data.size() / static_cast<std::size_t>(subSize)) return false;
            length = count * subSize;
        } else {
            length = typeSize(type);
            if (length < 0) return false;
        }

        if (length < 0 || static_cast<std::size_t>(length) > data.size() - off) return false;
        const std::size_t n = static_cast<std::size_t>(length);
        u8 *raw = const_cast<u8 *>(data.data()) + off;
        for (std::size_t i = 0; i < n; ++i) raw[i] ^= rng.next();
        if (key == wantedKey) {
            out.found = true;
            out.key = key;
            out.type = type;
            out.data = raw;
            out.size = n;
        }
        off += n;
    }
    return off == data.size();
}

inline int countLumiosePokedex(const BlockView &dex) {
    if (!dex.found || dex.type != 4 || dex.data == nullptr) return -1;
    const std::size_t entries = dex.size / POKEDEX_ENTRY_SIZE;
    int count = 0;
    for (u32 index : LUMIOSE_DEX_INTERNAL) {
        if (index >= entries) return -1;
        const u8 *entry = dex.data + static_cast<std::size_t>(index) * POKEDEX_ENTRY_SIZE;
        if (readU32(entry + CAUGHT_FLAG_OFFSET) != 0) ++count;
    }
    return count;
}

